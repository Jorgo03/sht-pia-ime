// Step 4 of the locations audit: writes src/features/properties/data/locations.js,
// the list both apps offer, from data/albania-locations.json and the
// decisions approved at Checkpoint 1 (docs/locations/decisions.json).
//
// A city is a municipality (bashki), all 61 of them, named after its seat
// town as the app always has (Peshkopi for Bashkia Dibër). Its zones are:
// its official units (except the seat's own, which is the city itself), its
// lagje, and every zone the app already offered that was approved, under the
// municipality it really belongs to.
//
//   node scripts/locations/generate-app-list.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = path.join(root, 'src/features/properties/data/locations.js')
const dataset = JSON.parse(fs.readFileSync(path.join(root, 'data/albania-locations.json'), 'utf8'))
const { decisions } = JSON.parse(fs.readFileSync(path.join(root, 'docs/locations/decisions.json'), 'utf8'))
const byId = new Map(dataset.locations.map((e) => [e.id, e]))
const fold = (s) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[-‐–]/g, ' ').replace(/\s+/g, ' ').trim()
const bashkiOf = (e) => { let x = e; while (x && x.type !== 'bashki') x = byId.get(x.parent_id); return x }
/** Latin-script search keys only: folded names and aliases, no duplicates. */
const keys = (e, extra = []) => [...new Set([e.name.indefinite, e.name.definite, ...e.aliases, ...extra].map(fold))].filter((a) => a && /^[a-z0-9 .']+$/.test(a)).sort()

// The approved zones, as dataset entries, and the name the app used to give
// each one ("Laprakë" for Lapraka), kept as a search key.
const approved = new Set()
const oldNames = new Map()
for (const d of decisions) {
  if (d.action === 'remove') continue
  for (const t of d.to) {
    const name = t.as ?? t.name
    const e = dataset.locations.find((x) => x.source.osm === t.osm && fold(x.name.indefinite) === fold(name)) ??
      dataset.locations.find((x) => x.source.osm === t.osm)
    if (!e) throw new Error(`approved zone ${d.city}/${d.zone} (${t.osm}) is not in the dataset`)
    approved.add(e.id)
    oldNames.set(e.id, [...(oldNames.get(e.id) ?? []), d.zone])
  }
}

const ZONE_TYPES = new Set(['njesi', 'lagje', 'zone'])
const cities = []
for (const b of dataset.locations.filter((e) => e.type === 'bashki')) {
  const seat = b.seat ?? b.name.indefinite
  const city = seat
  const zones = new Map()
  for (const e of dataset.locations) {
    if (e === b || !(ZONE_TYPES.has(e.type) || approved.has(e.id)) || bashkiOf(e) !== b) continue
    if (e.type === 'fshat' && !approved.has(e.id)) continue
    const k = fold(e.name.indefinite)
    // The seat's own unit is the city itself.
    if (k === fold(city) || k === fold(b.name.indefinite)) continue
    if (zones.has(k)) continue
    // "Razëm (Vrith)": OpenStreetMap's note of the village a hamlet is in.
    const name = e.name.indefinite.replace(/\s*\(.*\)$/, '')
    if (zones.has(fold(name))) continue
    zones.set(fold(name), {
      name,
      id: e.id,
      type: e.type,
      lat: e.centroid.lat,
      lng: e.centroid.lng,
      keys: keys(e, [name, ...(oldNames.get(e.id) ?? [])]),
    })
  }
  const sorted = [...zones.values()].sort((x, y) => x.name.localeCompare(y.name, 'sq'))
  cities.push({
    city,
    label: fold(seat) === fold(b.name.indefinite) ? seat : `${seat} (${b.name.indefinite})`,
    bashki: b.name.indefinite,
    id: b.id,
    qark: byId.get(b.parent_id).name.indefinite,
    names: b.names,
    lat: b.centroid.lat,
    lng: b.centroid.lng,
    bbox: b.bbox,
    keys: keys(b, [seat]),
    zones: sorted,
  })
}
cities.sort((x, y) => x.city.localeCompare(y.city, 'sq'))

const zoneCount = cities.reduce((n, c) => n + c.zones.length, 0)
const body = `// GENERATED by scripts/locations/generate-app-list.mjs from
// data/albania-locations.json (OpenStreetMap ${dataset.snapshot}, Law 115/2014)
// and docs/locations/decisions.json. Do not edit by hand: change the sources
// and run the script. docs/locations/SOURCES.md explains every field.
//
// ${cities.length} cities (one per municipality, named after its seat town) and
// ${zoneCount} zones (official units, lagje, and the approved zones).
//
// CITIES[i]: { city, label, bashki, id, qark, names, lat, lng, bbox, keys, zones }
//   zones[j]: { name, id, type, lat, lng, keys }
//   id      the row in public.locations
//   keys    folded (lowercase, no diacritics) names and aliases, for search
//   bbox    [minLat, minLng, maxLat, maxLng] of the municipality's outline

export const CITIES = ${JSON.stringify(cities)}

/** The shape the pickers have always used: [{ city, zones: [name] }]. */
const LOCATIONS = CITIES.map((c) => ({ city: c.city, zones: c.zones.map((z) => z.name) }))

export default LOCATIONS
`
fs.writeFileSync(OUT, body)
console.log(`wrote ${path.relative(root, OUT)}: ${cities.length} cities, ${zoneCount} zones, ${(body.length / 1024).toFixed(0)} KB`)

// The AI assistant is deployed on its own and cannot import src/: it gets
// the city names and their search keys only.
const AI = path.join(root, 'supabase/functions/ai-assistant/places.js')
const cityKeys = {}
for (const c of cities) for (const k of c.keys) if (!cityKeys[k]) cityKeys[k] = c.city
fs.writeFileSync(AI, `// GENERATED by scripts/locations/generate-app-list.mjs; do not edit by hand.
// The app's ${cities.length} cities (src/features/properties/data/locations.js), keyed by
// every folded name and alias a person or the model may use for them:
// "tirana", "durazzo", "peshkopia", "diber" (for Peshkopi).
export const CITY_KEYS = ${JSON.stringify(cityKeys)}
`)
console.log(`wrote ${path.relative(root, AI)}: ${Object.keys(cityKeys).length} keys`)

// The database copy (public.locations): every dataset entry, with the city
// name the apps store for each municipality and whether a zone is offered.
const offered = new Map()
for (const c of cities) for (const z of c.zones) offered.set(z.id, z.name)
const appCity = new Map(cities.map((c) => [c.id, c.city]))
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`
const rows = dataset.locations.map((e) => {
  const b = bashkiOf(e)
  const display = offered.get(e.id) ?? e.name.indefinite
  return `(${[
    q(e.id), q(e.type), q(e.parent_id), q(b?.id ?? null), q(e.slug), q(display), q(e.name.definite),
    q(JSON.stringify(e.names)), arr(keys(e)), e.centroid?.lat ?? 'null', e.centroid?.lng ?? 'null',
    e.bbox ? `array[${e.bbox.join(',')}]::double precision[]` : 'null',
    q(e.postal_code), q(appCity.get(e.id) ?? null), offered.has(e.id) ? 'true' : 'false', q(JSON.stringify(e.source)),
  ].join(', ')})`
})
const SEED = path.join(root, 'supabase/pending/locations_seed.sql')
fs.writeFileSync(SEED, `-- GENERATED by scripts/locations/generate-app-list.mjs from
-- data/albania-locations.json; do not edit by hand. Fills public.locations
-- (supabase/pending/locations.sql). Re-running it updates every row in place.
insert into public.locations
  (id, type, parent_id, bashki_id, slug, name, name_definite, names, search_keys, lat, lng, bbox, postal_code, app_city, offered, source)
values
${rows.join(',\n')}
on conflict (id) do update set
  type = excluded.type, parent_id = excluded.parent_id, bashki_id = excluded.bashki_id, slug = excluded.slug,
  name = excluded.name, name_definite = excluded.name_definite, names = excluded.names, search_keys = excluded.search_keys,
  lat = excluded.lat, lng = excluded.lng, bbox = excluded.bbox, postal_code = excluded.postal_code,
  app_city = excluded.app_city, offered = excluded.offered, source = excluded.source;
`)
console.log(`wrote ${path.relative(root, SEED)}: ${rows.length} rows`)
