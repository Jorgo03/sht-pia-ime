// Writes docs/locations/VALIDATION_REPORT.md from docs/locations/validation.json
// (made by validate.mjs).
//   node scripts/locations/report.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const rows = JSON.parse(fs.readFileSync(path.join(root, 'docs/locations/validation.json'), 'utf8'))
const dataset = JSON.parse(fs.readFileSync(path.join(root, 'data/albania-locations.json'), 'utf8'))

const ORDER = ['missing', 'hierarchy', 'spelling', 'coords', 'unverified', 'valid']
const LABEL = { valid: '✅ valid', spelling: '✏️ misspelled', hierarchy: '🔁 wrong hierarchy', coords: '📍 bad coordinates', missing: '❌ does not exist', unverified: '❓ unverified' }
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

const count = (kind) => {
  const c = Object.fromEntries(ORDER.map((s) => [s, 0]))
  for (const r of rows.filter((x) => x.kind === kind)) c[r.status]++
  return c
}
const out = []
out.push('# Locations validation report')
out.push('')
out.push(`Step 3 of the locations audit. Every city and zone in \`src/features/properties/data/locations.js\`, the live listings' coordinates and the map default, checked against \`data/albania-locations.json\` (OpenStreetMap snapshot ${dataset.snapshot}, Law 115/2014 unit list) and Nominatim searches. Generated by \`node scripts/locations/validate.mjs && node scripts/locations/report.mjs\`; sources and method in \`SOURCES.md\`.`)
out.push('')
out.push('**Nothing has been changed yet.** This report only proposes. No live data is touched until it is approved.')
out.push('')
out.push('## Summary')
out.push('')
out.push(`| Status | Cities | Zones | Coordinates |`)
out.push('|---|---|---|---|')
const cc = count('city'), zc = count('zone'), kc = count('coordinates')
for (const s of ORDER) out.push(`| ${LABEL[s]} | ${cc[s]} | ${zc[s]} | ${kc[s]} |`)
out.push(`| **Total** | **${rows.filter((r) => r.kind === 'city').length}** | **${rows.filter((r) => r.kind === 'zone').length}** | **${rows.filter((r) => r.kind === 'coordinates').length}** |`)
out.push('')
out.push('What each status means here:')
out.push('')
out.push('- ✅ **valid**: a real place of that name lies inside the outline of the city\'s own municipality (bashki).')
out.push('- ✏️ **misspelled**: the place is real and in the right municipality, but spelled differently (proposed spelling given). "Probably" means one or two letters differ and it needs your confirmation.')
out.push('- 🔁 **wrong hierarchy**: real, but in a different municipality from the city it is listed under (within 40 km). The proposal says which city or municipality it belongs to.')
out.push('- 📍 **bad coordinates**: a point outside Albania, or outside its own municipality.')
out.push('- ❌ **does not exist**: no trace in any source checked. The proposal is to remove it. No replacement is invented.')
out.push('- ❓ **unverified**: something of that name exists, but not as a lagje or village (a street, a square, a beach, a lake, a market), or only other things are named after it. These need a decision or a local source (cadastre, the municipality) before keeping.')
out.push('')
out.push('None of the zones affects user data: the three live listings have no zone set. Tiranë and Durrës, the cities with listings, are both valid.')
out.push('')
for (const s of ORDER) {
  const list = rows.filter((r) => r.status === s)
  if (!list.length) continue
  out.push(`## ${LABEL[s]} (${list.length})`)
  out.push('')
  out.push('| Current value | Status | Where | Proposed real replacement | Evidence/source | Affects user data? (Y/N) |')
  out.push('|---|---|---|---|---|---|')
  for (const r of list) {
    const value = r.kind === 'zone' ? `${r.value} (zone of ${r.city})` : r.value
    out.push(`| ${cell(value)} | ${LABEL[s]} | \`${cell(r.where)}\` | ${cell(r.proposal)} | ${cell(r.evidence)} | ${r.userData} |`)
  }
  out.push('')
}
fs.writeFileSync(path.join(root, 'docs/locations/VALIDATION_REPORT.md'), out.join('\n'))
console.log('wrote docs/locations/VALIDATION_REPORT.md', { cities: cc, zones: zc, coordinates: kc })
